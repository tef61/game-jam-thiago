    function showGame(player) {
      var f = $("join-form"), g = $("phone");
      if (f) f.style.display = "none";
      if (g) g.style.display = "";
      document.documentElement.style.setProperty("--me", player.color);
      var tag = $("me-tag");
      if (tag) tag.innerHTML = '<span class="me-dot"></span>' + (player.slot ? "Player " + player.slot : "Watching") + " &middot; " + esc(player.name);
    }

    function start(name) {
      if (t) return;
      myName = name;
      sset("arc585_autojoin_" + code, name);
      var st = $("jf-status");
      if (st) st.textContent = "Connecting...";
      var btn = $("jf-go"); if (btn) btn.disabled = true;
      t = makeTransport(code, id);
      if (!t) { if (btn) btn.disabled = false; return; }
      var startedAt = Date.now();
      t.connect(onMsg, onPresence, { id: id, role: "phone" }).then(function () {
        if (st) st.textContent = "Looking for the screen...";
        sendJoin();
        retry = setInterval(function () {
          if (ready) return;
          sendJoin();
          if (st && Date.now() - startedAt > 6000 && !lastHeard) st.textContent = "Still looking for the screen. Is the room code right, and is the screen page open?";
        }, JOIN_RETRY_MS);
      }).catch(function (e) { connectFailed(e); t = null; if (btn) btn.disabled = false; });
    }

    showForm();
    // Auto-join: test phones, and reloads of a phone that already joined this room.
    var auto = sget("arc585_autojoin_" + code);
    if (code.length === 4 && (testTab || auto)) {
      start(testTab ? ("Test " + String(testTab).slice(-3).toUpperCase()) : auto);
    }
    return me;

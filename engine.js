/* =====================================================================
   ENGINE.JS  -  ARC 585 Game Jam starter
   ---------------------------------------------------------------------
   DO NOT EDIT THIS FILE. (Agents: this means you too. See AGENTS.md.)

   It does the plumbing so you can spend your hour on the game:
   - makes a room code and a QR code on the screen
   - lets phones join, assigns Player 1 to 4 (5th and later = spectator)
   - remembers players if a phone or the screen reloads
   - carries moves from phones to the screen, and messages back
   - notices when a phone disconnects or comes back

   Your game lives in screen-game.js and play-game.js.

   SCREEN SIDE (screen-game.js):
     const room = Jam.host({
       maxPlayers: 4,                 // 1 to 4
       onPlayerJoin(player)   {},     // player = {id, name, slot, color, role, connected}
       onPlayerLeave(player)  {},     // phone disconnected (may come back)
       onPlayerReturn(player) {},     // same phone came back
       onMove(player, type, data) {}  // a phone sent a move
     });
     room.players()                  -> players (role "player") in slot order
     room.spectators()               -> spectators (joined after 4 players)
     room.send(type, data)           -> message to every phone
     room.sendTo(player, type, data) -> message to one phone
     room.showJoin(true or false)    -> show or hide the join panel (QR + code)
     room.code                       -> the 4-letter room code

   PHONE SIDE (play-game.js):
     const me = Jam.join({
       onReady(player)       {},  // you're in. player.slot is 1-4 (0 = spectator)
       onMessage(type, data) {},  // the screen sent you something
       onScreenLost()        {}   // the screen went away (optional)
     });
     me.send(type, data)  -> send a move to the screen
     me.player            -> your player info once ready

   The game API is the global object "Jam" (not "Engine", so it never
   clashes with libraries like Matter.js that use that name).

   SPEED LIMIT: Supabase's free plan allows about 100 messages per second
   for the whole project. So the engine limits each message TYPE to
   5 per second from each phone and 10 per second from the screen.
   If the same type is sent again too fast, only the LATEST one is
   delivered. That means:
   - treat each type as "the latest value of X": e.g. "state" carries the
     whole current state, "taps" carries a running total;
   - never send two different events with the same type back to back
     (use different types, e.g. "phase" and "result");
   - send when something changes, never every animation frame.

   SOUND (screen side, optional):
     Jam.sound.unlock()        -> call inside a click (your Start button)
     Jam.sound.beep(freq, ms)  -> a simple beep, e.g. beep(660, 120)

   PRACTICE MODE: add ?practice=1 to the address. Tabs on this one
   computer talk to each other with no internet and no Supabase.
   Real phones cannot join in practice mode.
   ===================================================================== */


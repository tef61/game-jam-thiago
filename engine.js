  var audioCtx = null;
  var sound = {
    unlock: function () {
      try {
        if (!audioCtx) audioCtx = new (window.AudioContext || window.webkitAudioContext)();
        if (audioCtx.state === "suspended") audioCtx.resume();
      } catch (e) {}
    },
    beep: function (freq, ms) {
      try {
        if (!audioCtx) return;
        var o = audioCtx.createOscillator(), g = audioCtx.createGain();
        o.frequency.value = freq || 660; o.type = "square"; g.gain.value = 0.06;
        o.connect(g); g.connect(audioCtx.destination);
        o.start(); o.stop(audioCtx.currentTime + (ms || 120) / 1000);
      } catch (e) {}
    }
  };

  function reportGameError(e) {
    console.error("[your game code]", e);
    banner("warn", "<b>Error in your game code:</b> " + esc(e && e.message) + " (details in the browser console). Copy this message to your agent.");
  }
  function call(fn) {
    if (!fn) return;
    var args = Array.prototype.slice.call(arguments, 1);
    try { fn.apply(null, args); } catch (e) { reportGameError(e); }
  }

  // =====================================================================
  // SCREEN (host)
  // =====================================================================
  function host(opts) {
    opts = opts || {};
    var maxPlayers = Math.max(1, Math.min(4, opts.maxPlayers || 4));
    var code = String(params().get("room") || sget("arc585_room") || makeCode()).toUpperCase().replace(/[^A-Z]/g, "").slice(0, 4);
    if (code.length !== 4) code = makeCode();
    sset("arc585_room", code);
    var screenId = sget("arc585_screen_id") || makeId();
    sset("arc585_screen_id", screenId);

    var roster = {};   // id -> player
    var previous = {}; // players from before a screen reload
    try { previous = JSON.parse(sget("arc585_roster_" + code) || "{}"); } catch (e) { previous = {}; }
    function saveRoster() { sset("arc585_roster_" + code, JSON.stringify(roster)); }

    var t = makeTransport(code, screenId);
    // Messages sent before the connection is up wait in a queue.
    var linkReady = false, outbox = [];
    var rawSend = function (p) {
      if (!t) return;
      if (!linkReady) { outbox.push(p); return; }
      t.send(p);
    };
    var throttled = throttler(SCREEN_THROTTLE_MS, rawSend);

    function all() { return Object.keys(roster).map(function (k) { return roster[k]; }); }
    function clean(p) { return { id: p.id, name: p.name, slot: p.slot, color: p.color, role: p.role, connected: p.connected }; }
    var api = {
      code: code,
      players: function () {
        return all().filter(function (p) { return p.role === "player"; }).sort(function (a, b) { return a.slot - b.slot; }).map(clean);
      },
      spectators: function () { return all().filter(function (p) { return p.role === "spectator"; }).map(clean); },
      send: function (type, data) {
        throttled("all:" + type, function () { return { k: "msg", to: null, type: type, data: data === undefined ? null : data }; });
      },
      sendTo: function (player, type, data) {
        if (!player) return;
        throttled(player.id + ":" + type, function () { return { k: "msg", to: player.id, type: type, data: data === undefined ? null : data }; });
      },
      showJoin: function (on) { var j = $("join-panel"); if (j) j.style.display = on ? "" : "none"; }
    };

    function usedSlots() { return all().filter(function (p) { return p.role === "player"; }).map(function (p) { return p.slot; }); }
    function slotFree(s) { return s >= 1 && s <= maxPlayers && usedSlots().indexOf(s) < 0; }
    function firstFreeSlot() { for (var s = 1; s <= maxPlayers; s++) if (slotFree(s)) return s; return 0; }
    function longestAwayPlayer() {
      var away = all().filter(function (p) { return p.role === "player" && !p.connected; });
      away.sort(function (a, b) { return (a.awaySince || 0) - (b.awaySince || 0); });
      return away[0] || null;
    }

    function assign(id, name) {
      name = String(name || "Player").slice(0, 16);
      var p = roster[id];
      if (p) {
        var wasAway = !p.connected;
        p.connected = true; p.name = name; p.missingSince = null;
        finish(p);
        if (wasAway) call(opts.onPlayerReturn, clean(p));
        return;
      }
      var slot = firstFreeSlot();
      if (!slot) {
        // all seats taken: a newcomer takes the seat of whoever has been away longest
        var gone = longestAwayPlayer();
        if (gone) { slot = gone.slot; delete roster[gone.id]; }
      }
      p = { id: id, name: name, slot: slot, role: slot ? "player" : "spectator",
            color: slot ? COLORS[slot - 1] : SPECTATOR_COLOR, connected: true };
      roster[id] = p;
      finish(p);
      call(opts.onPlayerJoin, clean(p));
    }
    function finish(p) {
      saveRoster();
      rawSend({ k: "assigned", to: p.id, player: clean(p) });
      rawSend({ k: "roster", players: api.players(), spectators: api.spectators().length });
      renderPanel();
    }

    function onMsg(m) {
      if (!m || !m.k) return;
      if (m.k === "join" && m.id) assign(m.id, m.name);
      else if (m.k === "move" && m.id) {
        var p = roster[m.id];
        if (!p) return; // unknown phone: it will (re)join on its own
        p.missingSince = null;
        if (!p.connected) { p.connected = true; saveRoster(); renderPanel(); call(opts.onPlayerReturn, clean(p)); }
        call(opts.onMove, clean(p), m.type, m.data);
      }
    }
    // Presence can lag behind messages, so a phone only counts as "away"
    // after it has been missing from presence for AWAY_GRACE_MS in a row.
    var AWAY_GRACE_MS = 4000;
    var presentIds = [];
    function onPresence(metas) {
      presentIds = metas.map(function (m) { return m.id; });
      evaluatePresence();
    }
    function evaluatePresence() {
      var now = Date.now();
      all().forEach(function (p) {
        var isHere = presentIds.indexOf(p.id) >= 0;
        if (isHere) {
          p.missingSince = null;
          if (!p.connected) {
            p.connected = true; saveRoster(); renderPanel();
            call(opts.onPlayerReturn, clean(p));
          }
        } else if (p.connected) {
          if (!p.missingSince) p.missingSince = now;
          else if (now - p.missingSince > AWAY_GRACE_MS) {
            p.connected = false; p.awaySince = now; p.missingSince = null; saveRoster(); renderPanel();
            call(opts.onPlayerLeave, clean(p));
          }
        }
      });
    }
    setInterval(evaluatePresence, 1000);

    // ---------- join panel ----------
    function playUrl() {
      var base = location.href.split("#")[0].split("?")[0];
      base = base.substring(0, base.lastIndexOf("/") + 1);
      return base + "play.html?room=" + code + (isPractice() ? "&practice=1" : "");
    }
    function renderPanel() {
      var panel = $("join-panel");
      if (!panel) { // someone deleted it from screen.html: put it back
        panel = document.createElement("div");
        panel.id = "join-panel";
        panel.style.cssText = "position:fixed;right:20px;top:20px;z-index:1000";
        document.body.appendChild(panel);
      }
      var url = playUrl();
      var qrHtml = "";
      if (window.qrcode && !isPractice()) {
        try { var qr = window.qrcode(0, "M"); qr.addData(url); qr.make(); qrHtml = qr.createSvgTag({ cellSize: 6, margin: 2, scalable: true }); } catch (e) {}
      }
      var note = "";
      if (isPractice()) note = '<div class="jp-note">Practice mode: real phones can\'t join. Use test phones on this computer.</div>';
      else if (isLocal()) note = '<div class="jp-note">Running on this computer, so real phones can\'t open this address yet. The QR code works after you deploy. For now, use test phones.</div>';
      var players = api.players();
      var list = players.map(function (p) {
        return '<li style="--c:' + p.color + '" class="' + (p.connected ? "" : "jp-away") + '"><span class="jp-dot"></span>P' + p.slot + " " + esc(p.name) + (p.connected ? "" : " (away)") + "</li>";
      }).join("");
      for (var s = players.length; s < maxPlayers; s++) list += '<li class="jp-empty"><span class="jp-dot"></span>waiting...</li>';
      var nSpec = api.spectators().length;
      panel.innerHTML =
        (qrHtml ? '<div class="jp-qr">' + qrHtml + "</div>" : "") +
        '<div class="jp-info">' +
          '<div class="jp-label">Scan to join, or open</div>' +
          '<div class="jp-url">' + (isLocal() || isPractice() ? "play.html (after you deploy)" : esc(url.replace(/^https?:\/\//, "").split("?")[0])) + "</div>" +
          '<div class="jp-label">Room code</div><div class="jp-code" id="room-code">' + code + "</div>" +
          '<ul class="jp-list">' + list + "</ul>" +
          (nSpec ? '<div class="jp-spec">+ ' + nSpec + " watching</div>" : "") +
          '<button class="jp-test" id="add-test-phone" type="button">+ Add a test phone</button>' +
          note +
        "</div>";
      $("add-test-phone").onclick = function () { window.open(url + "&test=" + Date.now().toString(36), "_blank"); };
    }

    // After a screen reload: bring back everyone who was here, seats held, marked away
    // until their phone answers. Your game hears about them through onPlayerJoin.
    Object.keys(previous).forEach(function (id) {
      var p = previous[id];
      if (!p || !p.id) return;
      roster[id] = { id: p.id, name: p.name, slot: p.slot, role: p.role, color: p.color, connected: false, awaySince: Date.now() };
    });
    if (Object.keys(roster).length) {
      setTimeout(function () { all().forEach(function (p) { call(opts.onPlayerJoin, clean(p)); }); renderPanel(); }, 0);
    }

    renderPanel();
    if (t) {
      t.connect(onMsg, onPresence, { id: screenId, role: "screen" })
        .then(function () {
          linkReady = true;
          var waiting = outbox; outbox = [];
          t.send({ k: "hello" }); // phones already here rejoin
          waiting.forEach(function (p) { t.send(p); });
        })
        .catch(connectFailed);
    }
    return api;
  }

